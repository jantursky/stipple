import org.jetbrains.kotlin.gradle.ExperimentalWasmDsl
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

// The Compose part of the gallery: the examples, their controls and the catalog. The web page (:samples:web), the
// desktop window (:samples:desktop) and the phone apps (:samples:app) each host GalleryApp.
plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.compose.multiplatform)
    alias(libs.plugins.android.kmp.library)
}

// The gallery shows the example files it runs, so the source on the page is always the code that runs. They are
// read at build time into ExampleSources.kt, without their package and import lines.
val generatedSources = layout.buildDirectory.dir("generated/exampleSources")
val generateExampleSources by tasks.registering {
    val examples = layout.projectDirectory.dir("src/commonMain/kotlin/com/jantursky/stipple/samples/gallery/examples")
    val output = generatedSources
    inputs.dir(examples)
    outputs.dir(output)
    doLast {
        fun literal(text: String): String =
            buildString {
                append('"')
                text.forEach { c ->
                    when (c) {
                        '"' -> append("\\\"")
                        '\\' -> append("\\\\")
                        '$' -> append("\\$")
                        '\n' -> append("\\n")
                        '\t' -> append("    ")
                        else -> append(c)
                    }
                }
                append('"')
            }
        val files =
            examples.asFile
                .listFiles()
                .orEmpty()
                .filter { it.extension == "kt" }
                .sortedBy { it.name }
        val entries =
            files.joinToString(",\n") { file ->
                val body =
                    file
                        .readLines()
                        .dropWhile { it.startsWith("package ") || it.startsWith("import ") || it.isBlank() }
                        .joinToString("\n")
                "    ${literal(file.nameWithoutExtension)} to ${literal(body)}"
            }
        val target = output.get().asFile.resolve("com/jantursky/stipple/samples/gallery/ExampleSources.kt")
        target.parentFile.mkdirs()
        target.writeText(
            "package com.jantursky.stipple.samples.gallery\n\n" +
                "/** The examples' source, by file name, generated by the build. */\n" +
                "internal val ExampleSources: Map<String, String> = mapOf(\n$entries,\n)\n",
        )
    }
}

kotlin {
    android {
        namespace = "com.jantursky.stipple.samples.gallery"
        compileSdk =
            libs.versions.android.compileSdk
                .get()
                .toInt()
        minSdk =
            libs.versions.android.minSdk
                .get()
                .toInt()
        compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
        androidResources { enable = true }
    }

    jvm { compilerOptions { jvmTarget.set(JvmTarget.JVM_17) } }

    @OptIn(ExperimentalWasmDsl::class)
    wasmJs { browser() }

    iosArm64()
    iosSimulatorArm64()

    sourceSets {
        commonMain {
            kotlin.srcDir(generatedSources)
            dependencies {
                api(project(":stipple"))
                api(project(":stipple-components"))
                api(libs.compose.runtime)
                api(libs.compose.foundation)
                api(libs.compose.ui)
                implementation(libs.compose.animation)
                implementation(libs.compose.components.resources)
            }
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
        }
    }
}

tasks.matching { it.name.startsWith("compile") && it.name.contains("Kotlin") }.configureEach {
    dependsOn(generateExampleSources)
}
tasks.matching { it.name.endsWith("SourcesJar") || it.name.startsWith("ksp") || it.name.startsWith("lint") }.configureEach {
    dependsOn(generateExampleSources)
}

compose.resources {
