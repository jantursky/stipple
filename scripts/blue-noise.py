#!/usr/bin/env python3
"""Generates the blue-noise threshold texture embedded in the library (void-and-cluster, Ulichney 1993).

Usage: scripts/blue-noise.py > stipple/src/commonMain/kotlin/com/jantursky/stipple/internal/BlueNoiseData.kt
The texture is 64x64, tileable, and holds each rank 0..4095 exactly once. Output is deterministic.
"""
import numpy as np

N = 64
SIGMA = 1.9
RNG = np.random.default_rng(20261026)


def kernel():
    d = np.minimum(np.arange(N), N - np.arange(N)).astype(float)
    return np.exp(-(d[:, None] ** 2 + d[None, :] ** 2) / (2 * SIGMA**2))


K = kernel()


def energy(pattern):
    e = np.zeros((N, N))
    for r, c in zip(*np.nonzero(pattern)):
        e += np.roll(K, (r, c), axis=(0, 1))
    return e


def tightest(pattern, e):
    return np.unravel_index(np.argmax(np.where(pattern, e, -1)), e.shape)


def largest_void(pattern, e):
    return np.unravel_index(np.argmin(np.where(pattern, 1e9, e)), e.shape)


def toggle(pattern, e, pos, on):
    pattern[pos] = on
    e += (1 if on else -1) * np.roll(K, pos, axis=(0, 1))


def generate():
    total = N * N
    pattern = np.zeros((N, N), bool)
    pattern.flat[RNG.choice(total, total // 10, replace=False)] = True
    e = energy(pattern)
    while True:
        t = tightest(pattern, e)
        toggle(pattern, e, t, False)
        v = largest_void(pattern, e)
        toggle(pattern, e, v, True)
        if v == t:
            break
    ranks = np.zeros((N, N), int)
    ones = int(pattern.sum())

    work, we = pattern.copy(), e.copy()
    for rank in range(ones - 1, -1, -1):
        t = tightest(work, we)
        toggle(work, we, t, False)
        ranks[t] = rank

    work, we = pattern.copy(), e.copy()
    for rank in range(ones, total):
        v = largest_void(work, we)
        toggle(work, we, v, True)
        ranks[v] = rank
    return ranks


def main():
    ranks = generate()
    assert sorted(ranks.flat) == list(range(N * N))
    # Two hex digits would lose resolution (4096 ranks), so each value is four digits.
    text = "".join(f"{v:04x}" for v in ranks.flat)
    lines = [text[i : i + 96] for i in range(0, len(text), 96)]
    print("// Generated by scripts/blue-noise.py. Do not edit.")
    print("package com.jantursky.stipple.internal\n")
    print("internal const val BLUE_NOISE_SIZE = %d\n" % N)
    print("/** Ranks 0..%d of a %dx%d tileable blue-noise texture, four hex digits each, row by row. */" % (N * N - 1, N, N))
    print("internal val BLUE_NOISE_HEX: String =")
    print('    "" +')
    for i, line in enumerate(lines):
        print(f'        "{line}"' + (" +" if i < len(lines) - 1 else ""))


main()
